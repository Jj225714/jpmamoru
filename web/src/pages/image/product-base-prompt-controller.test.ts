import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { imageFilesForUpload, ProductBasePromptController } from "./product-base-prompt-controller";
import { PRODUCT_INFORMATION_EXAMPLES, formatProductInformation } from "@/lib/product-information-prompt";

const reference = (id: string) => ({ id, name: id, type: "image/png", dataUrl: `data:${id}` });
function deferred() {
    let resolve!: (text: string) => void;
    let reject!: (error: Error) => void;
    const promise = new Promise<string>((yes, no) => {
        resolve = yes;
        reject = no;
    });
    return { promise, resolve, reject };
}
describe("automatic product prompt", () => {
    beforeEach(() => vi.useFakeTimers());
    afterEach(() => vi.useRealTimers());
    it("restarts after team readiness sync and ignores prior account completion", async () => {
        const controller = new ProductBasePromptController();
        const old = deferred();
        const analyze = vi.fn().mockReturnValueOnce(old.promise).mockResolvedValueOnce("B information");
        controller.setReferences([reference("photo")]);
        controller.configure("account-A:unknown", false, analyze);
        await vi.advanceTimersByTimeAsync(300);
        expect(analyze).not.toHaveBeenCalled();
        controller.configure("account-A:ready", true, analyze);
        await vi.advanceTimersByTimeAsync(250);
        controller.configure("account-B:ready", true, analyze);
        await vi.advanceTimersByTimeAsync(250);
        old.resolve("A information");
        await vi.advanceTimersByTimeAsync(0);
        expect(controller.getSnapshot().prompt).toBe("B information");
        controller.configure("account-B:unsupported", false, analyze);
        controller.setPrompt("人工填写");
        expect(controller.canGenerate()).toBe(true);
    });
    it.each(["edit", "keep", "clear"])("preserves stale auto text and blocks generation until explicit %s", async (action) => {
        const analyze = vi.fn().mockResolvedValueOnce("A fields").mockResolvedValueOnce("B fields");
        const controller = new ProductBasePromptController();
        controller.configure("config", true, analyze);
        controller.setReferences([reference("A")]);
        await vi.advanceTimersByTimeAsync(250);
        expect(controller.canGenerate()).toBe(true);
        controller.setReferences([reference("B")]);
        controller.configure("changed model", true, analyze);
        await vi.advanceTimersByTimeAsync(500);
        expect(controller.getSnapshot()).toMatchObject({ prompt: "A fields", stale: true });
        expect(controller.canGenerate()).toBe(false);
        expect(analyze).toHaveBeenCalledTimes(1);
        if (action === "edit") controller.setPrompt("reviewed B fields");
        if (action === "keep") controller.keepCurrent();
        if (action === "clear") {
            controller.clearAndRetry();
            expect(controller.getSnapshot().prompt).toBe("");
            expect(controller.canGenerate()).toBe(false);
            await vi.advanceTimersByTimeAsync(250);
            expect(controller.getSnapshot().prompt).toBe("B fields");
            expect(analyze.mock.calls[1][0]).toEqual([reference("B")]);
        }
        expect(controller.getSnapshot().stale).toBe(false);
        expect(controller.canGenerate()).toBe(true);
        if (action === "keep") expect(controller.getSnapshot().prompt).toBe("A fields");
    });
    it("does not impose stale confirmation on manual text or edited auto text", async () => {
        const controller = new ProductBasePromptController();
        const analyze = vi.fn().mockResolvedValue("A fields");
        controller.configure("config", true, analyze);
        controller.setPrompt("manual");
        controller.setReferences([reference("A")]);
        expect(controller.canGenerate()).toBe(true);
        expect(controller.getSnapshot()).toMatchObject({ prompt: "manual", stale: false });
        controller.clearAndRetry();
        await vi.advanceTimersByTimeAsync(250);
        controller.setPrompt("edited A fields");
        controller.setReferences([reference("B")]);
        expect(controller.canGenerate()).toBe(true);
        expect(controller.getSnapshot()).toMatchObject({ prompt: "edited A fields", stale: false });
    });
    it("keeps manual clearing suppressed across config changes until explicit retry", async () => {
        const controller = new ProductBasePromptController();
        const analyze = vi.fn().mockResolvedValue("fields");
        controller.configure("A", true, analyze);
        controller.setReferences([reference("A")]);
        await vi.advanceTimersByTimeAsync(250);
        controller.setPrompt("");
        controller.configure("B", true, analyze);
        controller.configure("C", true, analyze);
        await vi.advanceTimersByTimeAsync(1000);
        expect(controller.getSnapshot().prompt).toBe("");
        expect(analyze).toHaveBeenCalledTimes(1);
        controller.retry();
        await vi.advanceTimersByTimeAsync(250);
        expect(controller.getSnapshot()).toMatchObject({ prompt: "fields", status: "done" });
        expect(analyze).toHaveBeenCalledTimes(2);
    });
    it("same semantic references and appending zero images do not abort pending analysis", async () => {
        const pending = deferred();
        const analyze = vi.fn((_refs: unknown, _signal: AbortSignal) => pending.promise);
        const controller = new ProductBasePromptController();
        controller.configure("config", true, analyze);
        controller.setReferences([reference("A")]);
        await vi.advanceTimersByTimeAsync(250);
        const snapshot = controller.getSnapshot();
        const signal = analyze.mock.calls[0][1] as AbortSignal;
        controller.setReferences((refs) => refs);
        controller.setReferences((refs) => [...refs, ...[]]);
        controller.setReferences([{ ...reference("A"), id: "new-ui-id", name: "renamed" }]);
        expect(controller.getSnapshot()).toBe(snapshot);
        expect(signal.aborted).toBe(false);
        pending.resolve("A fields");
        await vi.advanceTimersByTimeAsync(1000);
        expect(controller.getSnapshot()).toMatchObject({ prompt: "A fields", status: "done", stale: false });
        expect(analyze).toHaveBeenCalledTimes(1);
    });
    it("filters PDF-only and cancelled uploads to zero images", () => {
        expect(imageFilesForUpload([{ type: "application/pdf" } as File])).toEqual([]);
        expect(imageFilesForUpload(null)).toEqual([]);
        const image = { type: "image/png" } as File;
        expect(imageFilesForUpload([{ type: "application/pdf" } as File, image])).toEqual([image]);
    });
    it.each(PRODUCT_INFORMATION_EXAMPLES)("keeps all six fields editable for $name", async (information) => {
        const text = formatProductInformation(information);
        const controller = new ProductBasePromptController();
        controller.configure("config", true, vi.fn().mockResolvedValue(text));
        controller.setReferences([reference(information.name)]);
        await vi.advanceTimersByTimeAsync(250);
        expect(controller.getSnapshot()).toMatchObject({ prompt: text, status: "done" });
        controller.setPrompt(`${text}\n用户补充`);
        expect(controller.getSnapshot().prompt).toBe(`${text}\n用户补充`);
    });
    it("ignores late old references even if the transport ignores cancellation", async () => {
        const old = deferred();
        const next = deferred();
        const analyze = vi.fn().mockReturnValueOnce(old.promise).mockReturnValueOnce(next.promise);
        const controller = new ProductBasePromptController();
        controller.configure("config", true, analyze);
        controller.setReferences([reference("tent")]);
        await vi.advanceTimersByTimeAsync(250);
        const signal = analyze.mock.calls[0][1] as AbortSignal;
        controller.setReferences([reference("purifier")]);
        expect(signal.aborted).toBe(true);
        await vi.advanceTimersByTimeAsync(250);
        next.resolve("purifier fields");
        old.resolve("tent fields");
        await vi.advanceTimersByTimeAsync(0);
        expect(controller.getSnapshot().prompt).toBe("purifier fields");
    });
    it("never fills after typing then clearing, including batched edits", async () => {
        const pending = deferred();
        const analyze = vi.fn(() => pending.promise);
        const controller = new ProductBasePromptController();
        controller.configure("config", true, analyze);
        controller.setReferences([reference("armchair")]);
        await vi.advanceTimersByTimeAsync(250);
        controller.setPrompt("my edit");
        controller.setPrompt("");
        pending.resolve("old fields");
        controller.configure("config", true, analyze);
        await vi.advanceTimersByTimeAsync(1000);
        expect(controller.getSnapshot().prompt).toBe("");
        expect(analyze).toHaveBeenCalledTimes(1);
    });
    it("does not loop after failure; explicit retry fills the editable actual text", async () => {
        const analyze = vi.fn().mockRejectedValueOnce(new Error("friendly error")).mockResolvedValueOnce("blanket six fields");
        const controller = new ProductBasePromptController();
        controller.configure("config", true, analyze);
        controller.setReferences([reference("blanket")]);
        await vi.advanceTimersByTimeAsync(250);
        expect(controller.getSnapshot()).toMatchObject({ status: "error", error: "friendly error" });
        controller.configure("config", true, analyze);
        await vi.advanceTimersByTimeAsync(1000);
        expect(analyze).toHaveBeenCalledTimes(1);
        controller.retry();
        controller.retry();
        await vi.advanceTimersByTimeAsync(250);
        expect(analyze).toHaveBeenCalledTimes(2);
        expect(controller.getSnapshot()).toMatchObject({ status: "done", prompt: "blanket six fields" });
        controller.setPrompt("reviewed blanket");
        expect(controller.getSnapshot().prompt).toBe("reviewed blanket");
    });
    it("skips existing input, absent images and unconfigured models", async () => {
        const analyze = vi.fn();
        const controller = new ProductBasePromptController();
        controller.configure("config", true, analyze);
        await vi.advanceTimersByTimeAsync(500);
        controller.setPrompt("existing prompt");
        controller.setReferences([reference("tent")]);
        await vi.advanceTimersByTimeAsync(500);
        expect(controller.getSnapshot().prompt).toBe("existing prompt");
        controller.reset();
        controller.configure("missing", false, analyze);
        controller.setReferences([reference("tent")]);
        controller.retry();
        await vi.advanceTimersByTimeAsync(500);
        expect(analyze).not.toHaveBeenCalled();
    });
    it("debounces ref changes and StrictMode setup-cleanup-setup", async () => {
        const analyze = vi.fn().mockResolvedValue("fields");
        const controller = new ProductBasePromptController();
        controller.configure("config", true, analyze);
        controller.setReferences([reference("tent")]);
        controller.cancel();
        controller.configure("config", true, analyze);
        await vi.advanceTimersByTimeAsync(200);
        controller.setReferences([reference("tent"), reference("blanket")]);
        await vi.advanceTimersByTimeAsync(249);
        expect(analyze).not.toHaveBeenCalled();
        await vi.advanceTimersByTimeAsync(1);
        expect(analyze).toHaveBeenCalledTimes(1);
    });
    it.each(["reset", "restore", "remove", "reorder", "unmount", "config"])("invalidates pending work on %s", async (action) => {
        const pending = deferred();
        const analyze = vi.fn(() => pending.promise);
        const controller = new ProductBasePromptController();
        controller.configure("config", true, analyze);
        controller.setReferences([reference("tent"), reference("blanket")]);
        await vi.advanceTimersByTimeAsync(250);
        if (action === "reset") controller.reset();
        if (action === "restore") controller.restore("history prompt", [reference("armchair")]);
        if (action === "remove") controller.setReferences([]);
        if (action === "reorder") controller.setReferences((refs) => [...refs].reverse());
        if (action === "unmount") controller.cancel();
        if (action === "config") controller.configure("new config", true, analyze);
        pending.resolve("stale fields");
        await vi.advanceTimersByTimeAsync(0);
        expect(controller.getSnapshot().prompt).toBe(action === "restore" ? "history prompt" : "");
        controller.cancel();
    });
    it("offers retry for blank responses without automatic looping", async () => {
        const analyze = vi.fn().mockResolvedValue("  ");
        const controller = new ProductBasePromptController();
        controller.configure("config", true, analyze);
        controller.setReferences([reference("tent")]);
        await vi.advanceTimersByTimeAsync(1000);
        expect(controller.getSnapshot().status).toBe("error");
        expect(analyze).toHaveBeenCalledTimes(1);
        controller.retry();
        await vi.advanceTimersByTimeAsync(250);
        expect(analyze).toHaveBeenCalledTimes(2);
    });
});
